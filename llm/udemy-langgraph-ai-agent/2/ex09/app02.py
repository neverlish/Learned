from langchain_core.tools import tool
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage, ToolMessage

# ----------------------------------------------------------
# 날씨 조회 도구를 정의합니다.
# ----------------------------------------------------------
@tool
def get_weather(city: str) -> str:
    """주어진 도시의 현재 날씨를 조회합니다."""
    return f"{city}의 현재 날씨는 흐림, 18도입니다."


# ----------------------------------------------------------
# 사용할 도구 목록을 준비합니다.
# ----------------------------------------------------------
tools = [get_weather]

# ----------------------------------------------------------
# 모델을 준비하고 도구를 바인딩합니다.
# ----------------------------------------------------------
llm = ChatOpenAI(model="gpt-5.4-mini", temperature=0).bind_tools(tools)


# ----------------------------------------------------------
# 사용자 질문을 준비합니다.
# ----------------------------------------------------------
messages = [HumanMessage("서울 날씨 알려줘")]

# ----------------------------------------------------------
# 첫 번째 모델 호출입니다.
# ----------------------------------------------------------
ai_msg = llm.invoke(messages)

# ----------------------------------------------------------
# 모델 응답을 대화 기록에 추가합니다.
# ----------------------------------------------------------
messages.append(ai_msg)


# ----------------------------------------------------------
# tool_calls가 있으면 도구를 실행합니다.
# ----------------------------------------------------------
for tool_call in ai_msg.tool_calls:
    selected_tool = {"get_weather": get_weather}[tool_call["name"]]

    tool_result = selected_tool.invoke(tool_call)

    messages.append(tool_result)

# ----------------------------------------------------------
# 도구 결과까지 포함한 상태로 다시 모델을 호출합니다.
# ----------------------------------------------------------
final_response = llm.invoke(messages)

# ----------------------------------------------------------
# 최종 답변을 출력합니다.
# ----------------------------------------------------------
print(final_response.content)